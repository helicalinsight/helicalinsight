"""Verify prompt refactoring in helicalbi.sql_agent.prompt."""
from helicalbi.sql_agent.config import (
    CONTEXT_PLAN_PROMPT as CFG_CONTEXT_PLAN_PROMPT,
    PLAN_EXECUTION_RULES as CFG_PLAN_EXECUTION_RULES,
    SQL_SHAPE_DERIVED_TABLES as CFG_SQL_SHAPE_DERIVED_TABLES,
    SYNTHESIZER_PROMPT as CFG_SYNTHESIZER_PROMPT,
    THINK_FLAT_SQL_GENERATION as CFG_THINK_FLAT_SQL_GENERATION,
    THINK_FLAT_SQL_PLAN_RULES as CFG_THINK_FLAT_SQL_PLAN_RULES,
    TOOL_AGENT_PROMPT as CFG_TOOL_AGENT_PROMPT,
)
from helicalbi.sql_agent.prompt import (
    AUTO_MODE_PROMPT,
    CONTEXT_PLAN_PROMPT,
    PLAN_EXECUTION_RULES,
    SQL_SHAPE_DERIVED_TABLES,
    STEP_INSIGHT_PROMPT,
    SYNTHESIZER_PROMPT,
    THINK_FINAL_ANSWER_PROMPT,
    THINK_FLAT_SQL_GENERATION,
    THINK_FLAT_SQL_PLAN_RULES,
    THINK_FLAT_SQL_RETRY_DIRECTIVE,
    THINK_QUESTION_SYSTEM,
    THINK_SUBQUERY_REJECTION,
    THINK_SUCCESS_EXECUTION_PROMPT,
    THINK_SUCCESS_PROMPT_FORMATTED,
    TOOL_AGENT_PROMPT,
    _THINK_QUESTION_SYSTEM,
)
from helicalbi.sql_agent.prompt.think_prompts import (
    THINK_FINAL_ANSWER_PROMPT as TP_FINAL_ANSWER,
    THINK_FLAT_SQL_GENERATION as TP_FLAT_SQL,
    THINK_FLAT_SQL_PLAN_RULES as TP_PLAN_RULES,
    THINK_QUESTION_SYSTEM as TP_QUESTION_SYSTEM,
)


def test_prompts_match_config_exports():
    assert CONTEXT_PLAN_PROMPT == CFG_CONTEXT_PLAN_PROMPT
    assert PLAN_EXECUTION_RULES == CFG_PLAN_EXECUTION_RULES
    assert SQL_SHAPE_DERIVED_TABLES == CFG_SQL_SHAPE_DERIVED_TABLES
    assert SYNTHESIZER_PROMPT == CFG_SYNTHESIZER_PROMPT
    assert THINK_FLAT_SQL_GENERATION == CFG_THINK_FLAT_SQL_GENERATION
    assert THINK_FLAT_SQL_PLAN_RULES == CFG_THINK_FLAT_SQL_PLAN_RULES
    assert TOOL_AGENT_PROMPT == CFG_TOOL_AGENT_PROMPT


def test_think_prompts_contents():
    assert _THINK_QUESTION_SYSTEM == THINK_QUESTION_SYSTEM
    assert "Think investigation" in THINK_QUESTION_SYSTEM
    assert "one flat SELECT" in THINK_FLAT_SQL_PLAN_RULES
    assert "one flat SELECT" in THINK_FLAT_SQL_GENERATION
    assert "Subqueries are not allowed" in THINK_SUBQUERY_REJECTION
    assert "forbids subqueries" in THINK_FLAT_SQL_RETRY_DIRECTIVE
    assert "Conclusion" in THINK_FINAL_ANSWER_PROMPT
    assert "{format_instructions}" in THINK_FINAL_ANSWER_PROMPT
    assert "{sample_data}" in STEP_INSIGHT_PROMPT
    assert "{question}" in AUTO_MODE_PROMPT
    assert TP_QUESTION_SYSTEM == THINK_QUESTION_SYSTEM
    assert TP_PLAN_RULES == THINK_FLAT_SQL_PLAN_RULES
    assert TP_FLAT_SQL == THINK_FLAT_SQL_GENERATION
    assert TP_FINAL_ANSWER == THINK_FINAL_ANSWER_PROMPT
